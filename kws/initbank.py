"""The unit's own Init bank and Multi Mode Setup, embedded as bytes.

A factory-initialised Wavestation SR fills its RAM banks with this state:
every performance slot holds one Init performance, every patch slot one Init
patch, and the wave-sequence bank is zeroed. The Multi Mode Setup (32
Multisets) has its own derived Init template. kwsed builds these from bytes
literals so nothing reads a dump from a path at runtime.

**Why literals rather than a resource file.** The Init state is small
(two records, a zeroed pool, one Multi Mode Setup dump) and carried as
literals so the app stays self-contained. Digests pinned in
``tests/test_initbank.py`` guard against a silent edit.

The records were read once, during development, from SysEx bank dumps the
instrument itself produced, decoded with :func:`kws.importers.read_file`.
They are embedded verbatim below. Nothing here refers to where those dumps
live, and nothing at runtime opens a file.

``INIT_PERFORMANCE`` is one 181-byte record named ``Init``: part 0 points at
RAM 1 patch 0 and parts 1-7 are unused (patch 255). ``INIT_PATCH`` is one
426-byte record named ``Init``. A bank is 50 performances and 35 patches.
The wave-sequence bank is :data:`kws.records.WAVESEQ_BANK_SIZE` zero bytes.
``INIT_MULTISET`` is the Init Multi Mode Setup (32 Multisets, encoded): sets
0-15 use bank 0, perf ``m+c-1``, level 127 (group-A FX, control channel 0);
sets 16-31 use bank 1, perf 0, level ``m+c-1`` (group-B FX, control channel
127). Derived from the on-unit 2-31 template and confirmed by the user.
"""

